note "the callback surface is live and refuses a forged completion:"
STATUS=$(curl -sS -o /dev/null -w '%{http_code}' -X POST "$CALLBACK/decisions/$MFA_ID/challenges/0/mfa" \
  -H 'Content-Type: application/json' \
