# ---------------------------------------------------------------------------
# 11. M4: the authoring path, end to end
# ---------------------------------------------------------------------------

step "authoring a policy the way the console does, and taking it through approval"

# Both example transfer policies match this request on subject, resource and
# action; both exclude offshore in their condition. So the answer before the
# revision is a plain deny with no policy named, and after it the same request
# is a decision waiting on two approvers.
note "before the revision, an offshore transfer is denied outright:"
RESP=$(check dana 500 offshore)
assert_eq false "$(printf '%s' "$RESP" | jq -r .decision)" "check(dana, 500 offshore) before"
assert_eq condition_not_met "$(printf '%s' "$RESP" | jq -r '.context["stamp.reason"]')" "reason before"

OFFSHORE_DOC=$(cat <<'YAML'
apiVersion: stamp/v1
kind: Policy
id: offshore-transfer
description: Any transfer to an offshore destination needs two of the three named approvers.
subject: user
resource: transfer
actions:
  - execute
condition:
  left:
    field: resource.destination
  op: eq
  right: offshore
challenges:
  - type: quorum
    threshold: 2
    approvers:
      members:
        - ann
        - bob
        - cid
YAML
)

# This is the document the form builder produces: one change, `after` only. The
# `before` face is written by the server (D27) — a proposer who could state the
# past could write their own weakening classification.
REVISION_BODY=$(jq -n --arg after "$OFFSHORE_DOC" \
  '{delta: {changes: [{kind: "add", policy_id: "offshore-transfer", after: $after}]}}')

PREVIEW=$(curl -fsS -X POST "$CONSOLE/policies/revisions/preview" \
  -H "Authorization: Bearer $ANN_TOKEN" -H 'Content-Type: application/json' -d "$REVISION_BODY")
note "preview says: threshold $(printf '%s' "$PREVIEW" | jq -r .threshold), weakening=$(printf '%s' "$PREVIEW" | jq -r .weakening)"

PROPOSAL=$(curl -fsS -X POST "$CONSOLE/policies/revisions" \
  -H "Authorization: Bearer $ANN_TOKEN" -H 'Content-Type: application/json' -d "$REVISION_BODY")
REVISION_ID=$(printf '%s' "$PROPOSAL" | jq -er .id)
REV_DECISION=$(printf '%s' "$PROPOSAL" | jq -er .decision_id)
assert_eq pending "$(printf '%s' "$PROPOSAL" | jq -r .state)" "revision state on submission"
assert_eq form "$(printf '%s' "$PROPOSAL" | jq -r .origin)" "authoring origin"

note "the revision's own decision is in the approvers' inbox:"
INBOX=$(curl -fsS "$CONSOLE/decisions/inbox" -H "Authorization: Bearer $BOB_TOKEN")
assert_eq 1 "$(printf '%s' "$INBOX" | jq -r --arg id "$REV_DECISION" '[.items[]|select(.decision_id==$id)]|length')" \
  "inbox entries for the revision"

# The same call as the transfer approval above. A revision is governed by a
# decision, and the approval a governance quorum collects goes through the
# identical route with the identical binding hash — one pipeline, two authoring
# paths in front of it (D22).
approve "$REV_DECISION" "$BOB_TOKEN" >/dev/null
approve "$REV_DECISION" "$CID_TOKEN" >/dev/null

APPLIED=0
for _ in $(seq 1 90); do
  STATE=$(curl -fsS "$CONSOLE/policies/revisions/$REVISION_ID" -H "Authorization: Bearer $ANN_TOKEN" | jq -r .state)
  if [ "$STATE" = applied ]; then APPLIED=1; break; fi
  sleep 1
done
[ "$APPLIED" -eq 1 ] || die "the revision never took effect (last state: ${STATE:-unknown})"
ok "revision $REVISION_ID is in force"

note "and the answer changed, which is the only proof that matters:"
await_check '.context["stamp.reason"]' requires_decision dana 500 offshore \
  || die "the new policy never reached the check path"
assert_eq offshore-transfer "$(printf '%s' "$RESP" | jq -r '.context["stamp.policy_id"]')" "policy that answered after"
mark "form-authored revision approved and in force"

step "exporting the same set to files and applying it back unchanged"
stamp_cli policy export --dir /var/lib/stamp/export
EXPORTED=$(stamp_cli policy apply --dir /var/lib/stamp/export)
printf '%s\n' "$EXPORTED" | grep -q 'no change' \
  || die "re-applying the export proposed a revision; the round trip is not lossless:\n$EXPORTED"
ok "export → apply is a no-op: the two authoring paths agree on the same set"
mark "file round trip verified"

# ---------------------------------------------------------------------------
# 12. audit
# ---------------------------------------------------------------------------

step "verifying the audit chain against its signed checkpoints"
note "waiting for a checkpoint to be signed (the demo takes one every 10s)"
# Run the way an auditor runs it: the public key and a readable sink, and no
# signing key in the environment at all. That is the whole argument for
# checkpoints — whoever can rewrite the log can recompute every hash in it, and
# what they cannot do is produce this signature.
for _ in $(seq 1 40); do
  if "${COMPOSE[@]}" exec -T \
      -e STAMP_AUDIT_CHECKPOINT_KEY_FILE= \
      -e STAMP_AUDIT_CHECKPOINT_KEY_ID= \
      -e STAMP_AUDIT_CHECKPOINT_VERIFY_KEYS=demo-checkpoint=/var/lib/stamp/checkpoint.pub \
      stamp /stamp audit verify \
      --dsn "postgres://stamp:$DEMO_POSTGRES_PASSWORD@postgres:5432/stamp?sslmode=disable" \
      --sink /var/lib/stamp/checkpoints.jsonl >"$RUN_DIR/audit-verify.txt" 2>&1; then
    AUDIT_RC=0; break
  else
    # The capture has to be inside the else. After `fi` the status is the
    # status of the `if` statement, and an `if` whose condition was false with
    # no else exits 0 -- so a chain mismatch (6) read as a pass, and the
    # retry-on-7 loop below compared 0 to 7 and broke on the first pass.
    AUDIT_RC=$?
  fi
  [ "$AUDIT_RC" -eq 7 ] || break
  sleep 3
done
if [ "${AUDIT_RC:-1}" -ne 0 ]; then
  cat "$RUN_DIR/audit-verify.txt" >&2
  die "stamp audit verify exited $AUDIT_RC (0 verified, 6 mismatch, 7 no verdict)"
fi
sed -n '1,12p' "$RUN_DIR/audit-verify.txt" | sed 's/^/     /'
ok "stamp audit verify exited 0"
mark "audit chain verified"

