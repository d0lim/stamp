step "a policy set that reaches outside is refused when no egress is allowed"
# The gate is deployment configuration, not policy data (D21/R35): a schema
# names a source, an operator decides what that source may dial. With no
# allowlist there is no destination that passes, so the process refuses to come
# up at all rather than starting with a source it can never call.
EGRESS_LOG="$RUN_DIR/egress-refusal.txt"
if "${COMPOSE[@]}" run --rm --no-deps \
     -e STAMP_AUDIT_WRITER_ID=egress-probe \
     -e STAMP_INSTANCE_ID=egress-probe \
     -e STAMP_EGRESS_ALLOW= \
     -e STAMP_STREAM_SOURCES= \
     -e STAMP_INGEST_CREDENTIALS= \
     -e STAMP_FACT_SOURCES='[{"name":"sanctions_list","kind":"http","params":[{"name":"destination","type":"string"}],"returns":"list<string>","ttl":"60s","timeout":"2s","url":"https://sanctions.example/v1/list"}]' \
     stamp --roles=all >"$EGRESS_LOG" 2>&1; then
  cat "$EGRESS_LOG" >&2
  die "the process started with a remote fact source and no egress allowlist"
fi
grep -qi 'egress' "$EGRESS_LOG" || { cat "$EGRESS_LOG" >&2; die "the refusal did not name the egress gate"; }
ok "refused, naming the egress gate: $(grep -io 'egress[^"]*' "$EGRESS_LOG" | head -1 | cut -c1-90)"

step "no plaintext secret in what the deployment renders or logs"
LOGS=$("${COMPOSE[@]}" logs --no-color 2>/dev/null || true)
# An empty LOGS would make every match below miss and report a green scan it
# never performed -- the same shape as the audit guard above. The logs of a
# running stack are never empty, so emptiness means the read failed.
[ -n "$LOGS" ] || die "could not read the stack's logs; the secret scan would have passed without looking"
CONFIG_DOC=$(curl -fsS "$CONSOLE/console/config.json")
for name in DEMO_POSTGRES_PASSWORD DEMO_KEYCLOAK_ADMIN_PASSWORD DEMO_USER_PASSWORD \
            DEMO_PEP_CLIENT_SECRET DEMO_INGEST_CLIENT_SECRET; do
  value=${!name}
  case "$LOGS" in *"$value"*) die "$name appears in container logs" ;; esac
  case "$CONFIG_DOC" in *"$value"*) die "$name appears in the console configuration document" ;; esac
done
case "$LOGS" in *"BEGIN PRIVATE KEY"*) die "a private key appears in container logs" ;; esac
ok "five generated credentials and the checkpoint key: none of them in logs or in /console/config.json"
note "the console's configuration document names the API base and the IdP and nothing else:"
printf '%s' "$CONFIG_DOC" | jq -c . | sed 's/^/     /'

