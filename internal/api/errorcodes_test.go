package api_test

// errorcodes_test.go renders the `error` code vocabulary this package can put
// on the wire, and it is mounted-routes.json's sibling.
//
// The reason it exists is an incident rather than a principle. #51 removed
// `403 not_an_approver` from the approval surface; the console went on
// branching on it and stayed green, because the console's tests stub responses
// and a stub says whatever the test wrote. Nothing compared the two sides. The
// endpoint *set* has been machine-checked since #44 — internal/runtime renders
// the assembled registry into internal/release/testdata/mounted-routes.json and
// internal/release/routes_test.go compares it against the contract document —
// and the error vocabulary, which is the axis that actually broke, had no such
// check.
//
// It is not a type generation problem, which is why no generator was added. The
// console's TypeScript was internally consistent the entire time the branch was
// dead: generated types match field *shapes*, and no shape says whether a code
// can still be emitted. What says that is a set difference, and a set
// difference needs both sides enumerated. This file enumerates the server's.
//
// # Why it is derived and not written down
//
// A hand-written list goes wrong together with the thing it guards. This
// repository has already paid for that once, in a hand-written role-to-surface
// map in internal/release/chart_test.go that was wrong in exactly the way the
// chart it checked was wrong. So the list here is read out of the package's own
// syntax tree:
//
//   - every writeError(w, status, code, message) call site, and
//   - every return of the (status int, code, message string) tables —
//     approvalError, auditReadError, decisionError, mfaError and
//     noSuchDecision — whose codes are values and therefore appear at no call
//     site as a literal at all. Counting writeError literals alone undercounts,
//     which is the trap this scanner exists to avoid falling into.
//
// The surface a code can reach is derived the same way: the Routes() methods
// say which listener each handler is mounted on, and the intra-package call
// graph carries that surface to every function the handler reaches. A code the
// console can never receive is not a code the console has to handle, and the
// exemption list on the console side depends on being able to say which is
// which.
//
// # What it does not cover
//
// The scanner reads syntax, not types. It resolves a code that is a string
// literal or a package-level string constant; anything else fails the run
// rather than being dropped, because a scanner that silently skips what it does
// not understand is how an artifact ends up shorter than the truth. It says
// nothing about which codes are *reachable* at runtime — an error table row for
// a sentinel nothing returns any more is still counted, because proving
// otherwise is a whole-program question and the failure mode it would catch
// (a code the console handles that the server never actually raises) is far
// milder than the one this closes.

