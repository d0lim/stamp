// errorCodeDocumentVersion identifies the shape of this document, not the code
// set. The Node side refuses a version it does not understand rather than
// guessing at unfamiliar fields, which is the same rule public-endpoints.json
// follows.
const errorCodeDocumentVersion = 1

// emittedCode is one `error` code, with every HTTP status it is written under
// and every listener it can reach.
//
// Statuses are a set rather than one value because a code legitimately has more
// than one: `invalid_request` is a 400 when a body is malformed and a 413 when
// it is too large, and collapsing that would hide a real difference the moment
// somebody looked here to answer "what does this code mean".
type emittedCode struct {
	Code     string   `json:"code"`
	Statuses []int    `json:"statuses"`
	Surfaces []string `json:"surfaces"`
}

type errorCodeDocument struct {
	Version  int           `json:"version"`
	Note     string        `json:"note"`
	Surfaces []string      `json:"surfaces"`
	Codes    []emittedCode `json:"codes"`
}

