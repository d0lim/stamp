// surfacesOf walks the call graph forward from every mounted handler and
// returns, for each function, the listeners it can be reached from.
func (s *scan) surfacesOf() map[funcKey]map[string]bool {
	out := map[funcKey]map[string]bool{}
	for root, surfaces := range s.roots {
		for surface := range surfaces {
			var visit func(funcKey)
			seen := map[funcKey]bool{}
			visit = func(key funcKey) {
				if seen[key] {
					return
				}
				seen[key] = true
				if out[key] == nil {
					out[key] = map[string]bool{}
				}
				out[key][surface] = true
				for callee := range s.calls[key] {
					visit(callee)
				}
			}
			visit(root)
		}
	}
	return out
}

// render turns the scan into the document, and reports every way the scan is
// not trustworthy enough to render.
//
// The tripwires are all one failure mode: a generator that quietly renders less
// than the truth. An artifact that is short is worse than no artifact, because
// the console check downstream would then read the shortfall as "the console
// branches on a code the server cannot emit" and blame the wrong side.
func (s *scan) render() (errorCodeDocument, []string) {
	problems := append([]string(nil), s.problems...)
	problems = append(problems, s.strayBodies()...)
	reach := s.surfacesOf()

	type acc struct {
		statuses map[int]bool
		surfaces map[string]bool
	}
	codes := map[string]*acc{}

	for key, sites := range s.sites {
		surfaces := reach[key]
		if len(surfaces) == 0 {
			for _, st := range sites {
				problems = append(problems, fmt.Sprintf(
					"%s: %q is written by %s, which no mounted route reaches; either the route "+
						"table changed shape or this scanner lost the call graph edge that leads here",
					st.pos, st.code, key))
			}
			continue
		}
		for _, st := range sites {
			a := codes[st.code]
			if a == nil {
				a = &acc{statuses: map[int]bool{}, surfaces: map[string]bool{}}
				codes[st.code] = a
			}
			a.statuses[st.status] = true
			for surface := range surfaces {
				a.surfaces[surface] = true
			}
		}
	}

	// A writeError whose code is a value has to sit in a function that reads
	// one of the tables. If it does not, a code is going out that nothing in
	// this file ever saw.
	for key, positions := range s.forwarders {
		if s.reachesTable(key) {
			continue
		}
		for _, pos := range positions {
			problems = append(problems, fmt.Sprintf(
				"%s: writeError is called with a computed code in %s, and %s reaches no "+
					"(status, code, message) table; that code is in no artifact", pos, key, key))
		}
	}

	if len(codes) == 0 {
		problems = append(problems, "the scan found no error codes at all, which cannot be true "+
			"of this package: the scanner is broken, not the handlers")
	}
	surfacesSeen := map[string]bool{}
	for _, a := range codes {
		for surface := range a.surfaces {
			surfacesSeen[surface] = true
		}
	}
	for _, surface := range api.Surfaces() {
		if !surfacesSeen[string(surface)] {
			problems = append(problems, fmt.Sprintf(
				"no error code is attributed to the %s listener; every surface this binary "+
					"binds can refuse something, so this is the scan losing a surface", surface))
		}
	}

	doc := errorCodeDocument{
		Version:  errorCodeDocumentVersion,
		Note:     errorCodeNote,
		Surfaces: sortedKeys(surfacesSeen),
		Codes:    make([]emittedCode, 0, len(codes)),
	}
	for code, a := range codes {
		statuses := make([]int, 0, len(a.statuses))
		for st := range a.statuses {
			statuses = append(statuses, st)
		}
		sort.Ints(statuses)
		doc.Codes = append(doc.Codes, emittedCode{
			Code:     code,
			Statuses: statuses,
			Surfaces: sortedKeys(a.surfaces),
		})
	}
	sort.Slice(doc.Codes, func(i, j int) bool { return doc.Codes[i].Code < doc.Codes[j].Code })
	sort.Strings(problems)
	return doc, problems
}

// reachesTable reports whether a function can reach one of the error tables.
func (s *scan) reachesTable(from funcKey) bool {
	seen := map[funcKey]bool{}
	var visit func(funcKey) bool
	visit = func(key funcKey) bool {
		if seen[key] {
			return false
		}
		seen[key] = true
		if s.tables[key] {
			return true
		}
		for callee := range s.calls[key] {
			if visit(callee) {
				return true
			}
		}
		return false
	}
	return visit(from)
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func renderErrorCodes(doc errorCodeDocument) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

