// funcKey names a function inside the package: "Type.Method" for a method,
// "Func" for a package-level function, and "Type.Method$N" for a function
// literal written inside one. Names are enough because this is one package and
// a method name is unique within its receiver type.
type funcKey = string

type site struct {
	code   string
	status int
	pos    token.Position
}

type scan struct {
	fset  *token.FileSet
	files []*ast.File

	// consts maps a package-level identifier to its string value. It is what
	// resolves CodeNotInstalled, ApprovalRateLimitedCode and SurfaceConsole
	// without a type checker.
	consts map[string]string

	// errorBodies names the response types that carry a code in a field the
	// wire calls `error`. ErrorResponse is the one writeError builds; the
	// others are the surfaces that answer with a body of their own shape and
	// put a code in it anyway, which is how "count the writeError call sites"
	// silently misses a code (it missed `invalid_policy`).
	errorBodies map[string]bool
	// handledBodies are the error-body literals the scan read. Anything of
	// those types written anywhere else is reported rather than skipped.
	handledBodies map[token.Pos]bool

	// bodies holds every function the scanner walks, including the literals.
	bodies map[funcKey]*ast.BlockStmt
	// receivers maps a method's key to its receiver identifier, so that a
	// x.helper() call inside it resolves to Type.helper.
	receivers map[funcKey]string
	// tables holds the subset whose results are (int, string, string): the
	// error tables whose codes never appear at a writeError call site.
	tables map[funcKey]bool

	calls map[funcKey]map[funcKey]bool
	// roots maps a mounted handler to the listener it is mounted on.
	roots map[funcKey]map[string]bool

	sites map[funcKey][]site
	// forwarders are writeError call sites whose code is a value rather than a
	// literal. They emit nothing themselves; the table they read from does.
	forwarders map[funcKey][]token.Position

	problems []string
}

func (s *scan) reportf(pos token.Position, format string, args ...any) {
	s.problems = append(s.problems, fmt.Sprintf("%s: %s", pos, fmt.Sprintf(format, args...)))
}

// newScan parses the package's non-test sources and builds everything the
// rendering needs.
func newScan(dir string) (*scan, error) {
	s := &scan{
		fset:          token.NewFileSet(),
		consts:        map[string]string{},
		errorBodies:   map[string]bool{},
		handledBodies: map[token.Pos]bool{},
		bodies:        map[funcKey]*ast.BlockStmt{},
		receivers:     map[funcKey]string{},
		tables:        map[funcKey]bool{},
		calls:         map[funcKey]map[funcKey]bool{},
		roots:         map[funcKey]map[string]bool{},
		sites:         map[funcKey][]site{},
		forwarders:    map[funcKey][]token.Position{},
	}

	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", dir, err)
	}
	var files []*ast.File
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, perr := parser.ParseFile(s.fset, filepath.Join(dir, name), nil, parser.SkipObjectResolution)
		if perr != nil {
			return nil, fmt.Errorf("parse %s: %w", name, perr)
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return nil, fmt.Errorf("%s holds no non-test Go files", dir)
	}
	s.files = files

	for _, f := range files {
		s.collectConsts(f)
		s.collectErrorBodies(f)
	}
	for _, f := range files {
		s.collectFuncs(f)
	}
	for _, f := range files {
		s.collectRoots(f)
	}
	for key, body := range s.bodies {
		s.walkBody(key, body)
	}
	return s, nil
}

func (s *scan) collectConsts(f *ast.File) {
	for _, decl := range f.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.CONST {
			continue
		}
		for _, spec := range gen.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}
			for i, name := range vs.Names {
				if i >= len(vs.Values) {
					continue
				}
				if lit, ok := vs.Values[i].(*ast.BasicLit); ok && lit.Kind == token.STRING {
					if v, uerr := strconv.Unquote(lit.Value); uerr == nil {
						s.consts[name.Name] = v
					}
				}
			}
		}
	}
}

// collectErrorBodies finds the response types that carry a code in an `error`
// field.
//
// The type is found by its JSON tag rather than by a list of names, and the
// reason is the bug this method was added for. The first version of this
// scanner read writeError call sites and the error tables, and asserted that
// [ErrorResponse] was the only body built outside writeError — which was true,
// and beside the point. `invalid_policy` goes out at 400 inside a
// [DiagnosticsResponse], whose `error` field is the same field on the wire and
// a different Go type in here. The console's own set said the server emits it;
// the artifact did not. A generator that renders less than the truth is exactly
// what every tripwire in this file is aimed at, and it took a hand-written
// assumption to slip one past them.
func (s *scan) collectErrorBodies(f *ast.File) {
	for _, decl := range f.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}
		for _, spec := range gen.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			st, ok := ts.Type.(*ast.StructType)
			if !ok || st.Fields == nil {
				continue
			}
			for _, field := range st.Fields.List {
				if id, ok := field.Type.(*ast.Ident); !ok || id.Name != "string" {
					continue
				}
				if field.Tag == nil {
					continue
				}
				tag, err := strconv.Unquote(field.Tag.Value)
				if err != nil {
					continue
				}
				if strings.Contains(tag, `json:"error"`) || strings.Contains(tag, `json:"error,`) {
					s.errorBodies[ts.Name.Name] = true
				}
			}
		}
	}
}

// collectFuncs registers every declared function and every function literal
// inside one, so that a handler written inline is walked like any other.
func (s *scan) collectFuncs(f *ast.File) {
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Body == nil {
			continue
		}
		key := declKey(fn)
		s.bodies[key] = fn.Body
		if recv := receiverName(fn); recv != "" {
			s.receivers[key] = recv
		}
		if isErrorTable(fn.Type) {
			s.tables[key] = true
		}
		s.registerLiterals(key, fn.Body)
	}
}

// registerLiterals gives every function literal under a body its own key, so a
// writeError inside a closure is attributed to the function that holds it.
func (s *scan) registerLiterals(owner funcKey, body ast.Node) {
	n := 0
	ast.Inspect(body, func(node ast.Node) bool {
		lit, ok := node.(*ast.FuncLit)
		if !ok {
			return true
		}
		n++
		key := fmt.Sprintf("%s$%d", owner, n)
		s.bodies[key] = lit.Body
		s.edge(owner, key)
		return true
	})
}

// declKey renders a declaration's key. A method takes its receiver's type name,
// pointer or not, because the two are one method set here.
func declKey(fn *ast.FuncDecl) funcKey {
	if fn.Recv == nil || len(fn.Recv.List) == 0 {
		return fn.Name.Name
	}
	return typeName(fn.Recv.List[0].Type) + "." + fn.Name.Name
}

func typeName(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.StarExpr:
		return typeName(t.X)
	case *ast.Ident:
		return t.Name
	case *ast.IndexExpr:
		return typeName(t.X)
	}
	return ""
}

// isErrorTable reports whether a signature is one of the (status int, code,
// message string) tables. It is matched on the shape rather than on a name
// list, so a fifth table added tomorrow is scanned without this file changing.
func isErrorTable(ft *ast.FuncType) bool {
	if ft.Results == nil {
		return false
	}
	var kinds []string
	for _, field := range ft.Results.List {
		id, ok := field.Type.(*ast.Ident)
		if !ok {
			return false
		}
		n := len(field.Names)
		if n == 0 {
			n = 1
		}
		for i := 0; i < n; i++ {
			kinds = append(kinds, id.Name)
		}
	}
	return len(kinds) == 3 && kinds[0] == "int" && kinds[1] == "string" && kinds[2] == "string"
}

func (s *scan) edge(from, to funcKey) {
	if s.calls[from] == nil {
		s.calls[from] = map[funcKey]bool{}
	}
	s.calls[from][to] = true
}

// collectRoots reads the Routes() methods and records which listener each
// mounted handler answers on.
//
// A route's Handler is not always a bare method value — the console wraps its
// handlers in a header middleware, and one is an inline literal — so the whole
// Handler expression is walked and everything function-shaped in it becomes a
// root. Missing a wrapper would only lose surfaces, and a lost surface is a
// code that looks unreachable, which the reachability tripwire below turns into
// a failure rather than a quiet hole.
func (s *scan) collectRoots(f *ast.File) {
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Name.Name != "Routes" || fn.Recv == nil || fn.Body == nil {
			continue
		}
		recv := receiverName(fn)
		self := typeName(fn.Recv.List[0].Type)
		owner := declKey(fn)
		// registerLiterals numbered every function literal in this body in
		// source order; the counter here walks the same order, so an inline
		// handler is matched to the body that was registered for it.
		literals := 0

		ast.Inspect(fn.Body, func(node ast.Node) bool {
			// The literal is written `[]Route{{…}, {…}}`, so the elements
			// carry no type of their own: the slice's element type is what
			// identifies them. Matching the elements directly would find
			// nothing, which is how a scanner ends up attributing every code
			// to no surface at all.
			slice, ok := node.(*ast.CompositeLit)
			if !ok {
				return true
			}
			arr, ok := slice.Type.(*ast.ArrayType)
			if !ok {
				return true
			}
			if name, ok := arr.Elt.(*ast.Ident); !ok || name.Name != "Route" {
				return true
			}
			for _, elt := range slice.Elts {
				route, ok := elt.(*ast.CompositeLit)
				if !ok {
					s.reportf(s.fset.Position(elt.Pos()),
						"a Routes() element is not a literal this scanner can read")
					continue
				}
				s.collectRoute(owner, recv, self, route, &literals)
			}
			return false
		})
	}
}

// collectRoute reads one Route literal: which listener it is on, and what
// function answers it.
func (s *scan) collectRoute(owner funcKey, recv, self string, cl *ast.CompositeLit, literals *int) {
	surface, handler := "", ast.Expr(nil)
	routeName := ""
	for _, elt := range cl.Elts {
		kv, ok := elt.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		key, ok := kv.Key.(*ast.Ident)
		if !ok {
			continue
		}
		switch key.Name {
		case "Surface":
			surface = s.resolveString(kv.Value)
		case "Handler":
			handler = kv.Value
		case "Name":
			routeName = s.resolveString(kv.Value)
		}
	}
	pos := s.fset.Position(cl.Pos())
	if surface == "" {
		s.reportf(pos, "route %q declares a Surface this scanner cannot resolve", routeName)
		return
	}
	if handler == nil {
		s.reportf(pos, "route %q declares no Handler", routeName)
		return
	}
	found := s.handlerRoots(owner, recv, self, handler, literals)
	if len(found) == 0 {
		s.reportf(pos, "route %q has a Handler shape this scanner cannot follow; "+
			"the codes it writes would be attributed to no surface", routeName)
	}
	for _, key := range found {
		if s.roots[key] == nil {
			s.roots[key] = map[string]bool{}
		}
		s.roots[key][surface] = true
	}
}

// handlerRoots returns every function reachable *syntactically* from a Handler
// expression: the receiver's own methods named in it, the package functions
// named in it, and any literal written inline.
func (s *scan) handlerRoots(owner funcKey, recv, self string, handler ast.Expr, literals *int) []funcKey {
	var out []funcKey
	ast.Inspect(handler, func(node ast.Node) bool {
		switch n := node.(type) {
		case *ast.SelectorExpr:
			if id, ok := n.X.(*ast.Ident); ok && id.Name == recv {
				key := self + "." + n.Sel.Name
				if _, known := s.bodies[key]; known {
					out = append(out, key)
				}
			}
		case *ast.Ident:
			if _, known := s.bodies[n.Name]; known {
				out = append(out, n.Name)
			}
		case *ast.FuncLit:
			*literals++
			key := fmt.Sprintf("%s$%d", owner, *literals)
			if _, known := s.bodies[key]; known {
				out = append(out, key)
			}
		}
		return true
	})
	return out
}

func receiverName(fn *ast.FuncDecl) string {
	if fn.Recv == nil || len(fn.Recv.List) == 0 || len(fn.Recv.List[0].Names) == 0 {
		return ""
	}
	return fn.Recv.List[0].Names[0].Name
}

// walkBody records what one function calls and what it emits.
func (s *scan) walkBody(key funcKey, body *ast.BlockStmt) {
	self := ""
	if i := strings.Index(key, "."); i > 0 {
		self = key[:i]
	}
	recv := s.receiverOf(key)

	ast.Inspect(body, func(node ast.Node) bool {
		switch n := node.(type) {
		case *ast.FuncLit:
			// Registered and walked under its own key.
			return false
		case *ast.SelectorExpr:
			if id, ok := n.X.(*ast.Ident); ok && recv != "" && id.Name == recv {
				if callee := self + "." + n.Sel.Name; s.bodies[callee] != nil {
					s.edge(key, callee)
				}
			}
		case *ast.Ident:
			if s.bodies[n.Name] != nil {
				s.edge(key, n.Name)
			}
		case *ast.CallExpr:
			s.collectWriteError(key, n)
			s.collectWriteJSON(key, n)
		case *ast.ReturnStmt:
			if s.tables[key] {
				s.collectTableReturn(key, n)
			}
		}
		return true
	})
}

// receiverOf recovers the receiver identifier for a method key, so that a
// x.helper() call inside it resolves to Type.helper.
func (s *scan) receiverOf(key funcKey) string {
	// Function literals inherit their owner's receiver: `$N` is appended to the
	// owner's key, and the closure sees the same identifier.
	base := key
	if i := strings.Index(base, "$"); i > 0 {
		base = base[:i]
	}
	return s.receivers[base]
}

func (s *scan) collectWriteError(key funcKey, call *ast.CallExpr) {
	id, ok := call.Fun.(*ast.Ident)
	if !ok || id.Name != "writeError" || len(call.Args) != 4 {
		return
	}
	pos := s.fset.Position(call.Pos())
	code := s.resolveString(call.Args[2])
	if code == "" {
		// A forwarded (status, code, message). The table it came from is
		// reached from this same function, and that is where the codes are
		// read; recorded so the tripwire below can insist that is true.
		s.forwarders[key] = append(s.forwarders[key], pos)
		return
	}
	status, ok := s.resolveStatus(call.Args[1])
	if !ok {
		s.reportf(pos, "writeError writes %q under a status this scanner cannot resolve; "+
			"write the http.Status constant at the call site so the artifact can state it", code)
		return
	}
	s.sites[key] = append(s.sites[key], site{code: code, status: status, pos: pos})
}

// collectWriteJSON reads the surfaces that answer a refusal with a body of
// their own shape.
//
// The status is what separates a code from a field that merely shares its name.
// [DryRunResponse] carries `error` too, and it is a sentence out of the
// evaluation trace rather than a vocabulary term — but it goes out with a 200,
// because the dry run succeeded and the policy is what did not. So the rule is
// the status: an `error` field on a refusal is a code, an `error` field on a
// success is a payload. That is derived from the call site rather than from a
// list of exempt types, which is the difference between a rule and a memory.
func (s *scan) collectWriteJSON(key funcKey, call *ast.CallExpr) {
	id, ok := call.Fun.(*ast.Ident)
	if !ok || id.Name != "writeJSON" || len(call.Args) != 3 {
		return
	}
	body, ok := call.Args[2].(*ast.CompositeLit)
	if !ok {
		return
	}
	name, ok := body.Type.(*ast.Ident)
	if !ok || !s.errorBodies[name.Name] {
		return
	}
	s.handledBodies[body.Pos()] = true

	// writeError is the generic writer: its code is a parameter, and every one
	// of its call sites is already read.
	if key == "writeError" {
		return
	}

	pos := s.fset.Position(call.Pos())
	status, ok := s.resolveStatus(call.Args[1])
	if !ok {
		s.reportf(pos, "a %s is written under a status this scanner cannot resolve; "+
			"whether its `error` field is a code depends on that status", name.Name)
		return
	}
	if status < http.StatusBadRequest {
		// A success carrying an `error` field. Not a refusal, not a code.
		return
	}
	code := ""
	for _, elt := range body.Elts {
		kv, ok := elt.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		if k, ok := kv.Key.(*ast.Ident); ok && k.Name == "Error" {
			code = s.resolveString(kv.Value)
		}
	}
	if code == "" {
		s.reportf(pos, "a %s goes out with status %d and this scanner cannot read the code in it",
			name.Name, status)
		return
	}
	s.sites[key] = append(s.sites[key], site{code: code, status: status, pos: pos})
}

// strayBodies reports every error-carrying response literal the scan did not
// read.
//
// It is the assumption underneath collectWriteJSON, checked rather than
// believed: these bodies reach the wire through writeJSON, so one built
// anywhere else — returned from a helper, stored in a variable, encoded by
// hand — is a code no set knows about.
func (s *scan) strayBodies() []string {
	var problems []string
	for _, f := range s.files {
		ast.Inspect(f, func(node ast.Node) bool {
			cl, ok := node.(*ast.CompositeLit)
			if !ok {
				return true
			}
			name, ok := cl.Type.(*ast.Ident)
			if !ok || !s.errorBodies[name.Name] {
				return true
			}
			if s.handledBodies[cl.Pos()] {
				return true
			}
			problems = append(problems, fmt.Sprintf(
				"%s: a %s is built somewhere other than a writeJSON argument; the scan reads "+
					"those call sites, so the code in this one is in no artifact",
				s.fset.Position(cl.Pos()), name.Name))
			return true
		})
	}
	return problems
}

func (s *scan) collectTableReturn(key funcKey, ret *ast.ReturnStmt) {
	if len(ret.Results) != 3 {
		// `return other()` — the delegation is an edge, and the callee's own
		// returns are read there.
		return
	}
	pos := s.fset.Position(ret.Pos())
	code := s.resolveString(ret.Results[1])
	if code == "" {
		s.reportf(pos, "an error table returns a code this scanner cannot resolve")
		return
	}
	status, ok := s.resolveStatus(ret.Results[0])
	if !ok {
		s.reportf(pos, "an error table returns %q under a status this scanner cannot resolve", code)
		return
	}
	s.sites[key] = append(s.sites[key], site{code: code, status: status, pos: pos})
}

// resolveString returns a string literal's value, or a package constant's, or
// "" when the expression is neither.
func (s *scan) resolveString(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.BasicLit:
		if e.Kind != token.STRING {
			return ""
		}
		v, err := strconv.Unquote(e.Value)
		if err != nil {
			return ""
		}
		return v
	case *ast.Ident:
		return s.consts[e.Name]
	}
	return ""
}

// resolveStatus reads an HTTP status out of the call site.
func (s *scan) resolveStatus(expr ast.Expr) (int, bool) {
	switch e := expr.(type) {
	case *ast.BasicLit:
		if e.Kind != token.INT {
			return 0, false
		}
		n, err := strconv.Atoi(e.Value)
		return n, err == nil
	case *ast.SelectorExpr:
		pkg, ok := e.X.(*ast.Ident)
		if !ok || pkg.Name != "http" {
			return 0, false
		}
		n, ok := httpStatusByName()[e.Sel.Name]
		return n, ok
	}
	return 0, false
}

// httpStatusByName inverts net/http's own status text table into the constant
// names the handlers write.
//
// It is derived rather than typed out for the same reason the code list is: a
// hand-written table of forty constants is a table that can be wrong, and the
// one thing worse than an unresolvable status is a status resolved to the wrong
// number. http.StatusText is the package's own data, and every constant except
// StatusTeapot (whose text is "I'm a teapot") is its text with the separators
// removed. StatusTeapot is not used here, and if it ever were, resolveStatus
// would fail loudly rather than guess.
func httpStatusByName() map[string]int {
	out := map[string]int{}
	replacer := strings.NewReplacer(" ", "", "-", "", "'", "")
	for n := 100; n < 600; n++ {
		text := http.StatusText(n)
		if text == "" {
			continue
		}
		out["Status"+replacer.Replace(text)] = n
	}
	return out
}

